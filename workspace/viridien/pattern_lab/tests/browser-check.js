async page => {
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.setViewportSize({width:1440,height:1000});
  await page.reload();
  await page.waitForFunction(()=>window.Strata?.state.doc && document.getElementById('scan').naturalWidth>0);
  await page.waitForLoadState('networkidle');
  const scrollCheck=await page.evaluate(async()=>{const v=document.getElementById('viewer'),before=Strata.state.y,requests=performance.getEntriesByType('resource').filter(r=>r.name.includes('/api/crop')).length;const t=performance.now();v.scrollTop+=24;await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));return{moved:Strata.state.y-before,frameMs:Math.round(performance.now()-t),newRequests:performance.getEntriesByType('resource').filter(r=>r.name.includes('/api/crop')).length-requests};});
  if(scrollCheck.moved<=0||scrollCheck.newRequests!==0)throw Error('Cached scroll did not move without crop requests: '+JSON.stringify(scrollCheck));
  const initial=await page.evaluate(()=>({document:Strata.state.doc.name,boxes:Strata.state.doc.segments.length,labels:Strata.state.doc.legend.length}));
  await page.getByRole('button',{name:/^Siltstone [0-9]+ boxes/}).click();
  await page.waitForFunction(()=>document.getElementById('scan').complete);
  await page.getByRole('button',{name:'+ Draw box',exact:true}).click();
  const plane=await page.evaluate(()=>{const p=document.getElementById('overlay').getBoundingClientRect(),v=document.getElementById('viewer').getBoundingClientRect();return{x:p.x,y:v.y,width:p.width,height:v.height};});
  await page.mouse.move(plane.x+plane.width*.44,plane.y+plane.height*.35);
  await page.mouse.down();
  await page.mouse.move(plane.x+plane.width*.63,plane.y+plane.height*.56,{steps:8});
  await page.mouse.up();
  if(!await page.evaluate(()=>Strata.flush()))throw Error('Save failed: '+await page.locator('#error').textContent());
  const created=await page.evaluate(()=>{const s=Strata.state.doc.segments.find(v=>v.id===Strata.state.selected);return {id:s.id,box:[...s.box],status:s.status,labels:s.legend_ids};});
  if(created.status!=='suggested'||created.labels[0]!==5)throw Error('New box did not use the active legend label');
  const handle=page.locator(`#overlay [data-id="${created.id}"][data-edge="bottom"]`);
  const edge=await handle.boundingBox();
  await page.mouse.move(edge.x+edge.width/2,edge.y+edge.height/2);
  await page.mouse.down();await page.mouse.move(edge.x+edge.width/2,edge.y+edge.height/2+32,{steps:6});await page.mouse.up();
  if(!await page.evaluate(()=>Strata.flush()))throw Error('Save failed: '+await page.locator('#error').textContent());
  const resized=await page.locator('#bottom').inputValue();
  if(Number(resized)<=created.box[3])throw Error('Bottom edge did not move');
  const topHandle=await page.locator(`#overlay [data-id="${created.id}"][data-edge="top"]`).boundingBox();
  await page.mouse.move(topHandle.x+topHandle.width/2,topHandle.y+topHandle.height/2);
  await page.mouse.down();await page.mouse.move(topHandle.x+topHandle.width/2,topHandle.y+topHandle.height/2+18,{steps:6});await page.mouse.up();
  if(!await page.evaluate(()=>Strata.flush()))throw Error('Save failed: '+await page.locator('#error').textContent());
  if(Number(await page.locator('#top').inputValue())<=created.box[1])throw Error('Top edge did not move');
  await page.getByRole('button',{name:'Accept segment',exact:true}).click();
  await page.getByRole('checkbox',{name:'Use as pattern source',exact:true}).check();
  await page.getByRole('textbox',{name:'Comment on selected box'}).fill('Browser check: both edges moved.');
  await page.getByRole('button',{name:'Add comment',exact:true}).click();
  if(!await page.evaluate(()=>Strata.flush()))throw Error('Save failed: '+await page.locator('#error').textContent());
  await page.reload();
  await page.waitForFunction(()=>window.Strata?.state.doc);
  const saved=await page.evaluate(id=>Strata.state.doc.segments.find(s=>s.id===id),created.id);
  if(!saved?.approved||!saved.example||saved.comments[0]?.text!=='Browser check: both edges moved.')throw Error('Save and reload failed');
  await page.evaluate(id=>Strata.select(id),created.id);
  await page.screenshot({path:'output/playwright/strata-editor-desktop.png',fullPage:false});
  await page.getByRole('button',{name:'Reject',exact:true}).click();
  if(!await page.evaluate(()=>Strata.flush()))throw Error('Save failed: '+await page.locator('#error').textContent());
  const rejected=await page.evaluate(()=>Strata.state.doc.segments.find(s=>s.id===Strata.state.selected));
  if(rejected.approved||rejected.example||rejected.status!=='rejected')throw Error('Reject did not remove source approval');
  await page.getByRole('button',{name:'Delete box',exact:true}).click();
  if(!await page.evaluate(()=>Strata.flush()))throw Error('Save failed: '+await page.locator('#error').textContent());
  await page.getByRole('combobox',{name:'Document',exact:true}).selectOption({index:1});
  await page.waitForFunction(()=>window.Strata.state.doc.name.includes('log01'));
  if((await page.locator('#segment-status').textContent())!=='Needs review')throw Error('Machine guesses were accepted');
  await page.getByRole('combobox',{name:'Document',exact:true}).selectOption({index:0});
  await page.waitForFunction(()=>window.Strata.state.doc.name.includes('hadrian'));
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.documentElement.clientWidth===390);
  const width=await page.evaluate(()=>({page:document.documentElement.scrollWidth,viewport:innerWidth}));
  if(width.page>width.viewport+2)throw Error('Phone layout has horizontal overflow: '+JSON.stringify(width));
  await page.screenshot({path:'output/playwright/strata-editor-phone.png',fullPage:false});
  if(errors.length)throw Error('Page errors: '+errors.join('; '));
  return {result:'PASS',scrollCheck,initial,createdBox:created.box,resizedBottom:Number(resized),savedAndReloaded:true,machineGuessNeedsReview:true,phoneWidth:width,checks:['draw','drag bottom','drag top','label','accept','pattern source','comment','save/reload','reject','delete','switch document','phone layout']};
}
